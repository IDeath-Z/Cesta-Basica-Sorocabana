-- ---------------------------------------------------------------------
-- Item registry
-- ---------------------------------------------------------------------

CREATE TABLE survey_type (
    id           smallint GENERATED BY DEFAULT AS IDENTITY,
    code         text     NOT NULL,
    name         text     NOT NULL,
    description  text,
    active       boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_survey_type      PRIMARY KEY (id),
    CONSTRAINT uq_survey_type_code UNIQUE (code)
);

COMMENT ON TABLE survey_type IS 'Tipo de coleta. Ex: Semanal, Páscoa, Natal';

CREATE TABLE unit (
    id        smallint      GENERATED BY DEFAULT AS IDENTITY,
    quantity  numeric(12,4) NOT NULL,
    measure   text          NOT NULL,
    active    boolean       NOT NULL DEFAULT true,

    CONSTRAINT pk_unit                  PRIMARY KEY (id),
    CONSTRAINT uq_unit_quantity_measure UNIQUE (quantity, measure),
    CONSTRAINT ck_unit_quantity         CHECK (quantity > 0)
);

COMMENT ON TABLE  unit         IS 'Unidade de venda do produto. Ex: 1 kg, 5 kg, 200 g, 8 unidades';
COMMENT ON COLUMN unit.measure IS 'Grandeza. Ex: kg, g, l, ml, un';

CREATE TABLE store (
    id      smallint GENERATED BY DEFAULT AS IDENTITY,
    name    text     NOT NULL,
    active  boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_store      PRIMARY KEY (id),
    CONSTRAINT uq_store_name UNIQUE (name)
);

COMMENT ON TABLE store IS 'Mercado pesquisado. Ex: Tauste, Bom Lugar';

CREATE TABLE category (
    id      smallint GENERATED BY DEFAULT AS IDENTITY,
    name    text     NOT NULL,
    active  boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_category      PRIMARY KEY (id),
    CONSTRAINT uq_category_name UNIQUE (name)
);

COMMENT ON TABLE category IS 'Categoria do produto. Ex: Alimentação, Higiene';

CREATE TABLE brand (
    id      integer GENERATED BY DEFAULT AS IDENTITY,
    name    text    NOT NULL,
    active  boolean NOT NULL DEFAULT true,

    CONSTRAINT pk_brand      PRIMARY KEY (id),
    CONSTRAINT uq_brand_name UNIQUE (name)
);

COMMENT ON TABLE brand IS 'Marca. Ex: Camil, Pilecco';

CREATE TABLE product (
    id             integer  GENERATED BY DEFAULT AS IDENTITY,
    category_id    smallint NOT NULL,
    unit_id        smallint,
    name           text     NOT NULL,
    specification  text,
    notes          text,
    active         boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_product           PRIMARY KEY (id),
    CONSTRAINT uq_product_name_spec UNIQUE NULLS NOT DISTINCT (name, specification),
    CONSTRAINT fk_product_category  FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT fk_product_unit      FOREIGN KEY (unit_id)     REFERENCES unit (id)
);

CREATE INDEX ix_product_category ON product (category_id);
CREATE INDEX ix_product_unit     ON product (unit_id);

COMMENT ON TABLE product IS 'Produto. Ex: Arroz, Creme Dental';

CREATE TABLE product_brand (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    product_id  integer NOT NULL,
    brand_id    integer NOT NULL,
    active      boolean NOT NULL DEFAULT true,

    CONSTRAINT pk_product_brand               PRIMARY KEY (id),
    CONSTRAINT uq_product_brand_product_brand UNIQUE (product_id, brand_id),
    CONSTRAINT fk_product_brand_product       FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_product_brand_brand         FOREIGN KEY (brand_id)   REFERENCES brand (id)
);

CREATE INDEX ix_product_brand_brand ON product_brand (brand_id);

COMMENT ON TABLE product_brand IS 'Combinação produto + marca que entra na pesquisa. Ex: Arroz Camil';

-- ---------------------------------------------------------------------
-- Survey
-- ---------------------------------------------------------------------

CREATE TABLE survey (
    id              integer     GENERATED BY DEFAULT AS IDENTITY,
    survey_date     date        NOT NULL,
    survey_type_id  smallint    NOT NULL,
    notes           text,
    draft           boolean     NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_survey             PRIMARY KEY (id),
    CONSTRAINT uq_survey_date_type   UNIQUE (survey_date, survey_type_id),
    CONSTRAINT fk_survey_survey_type FOREIGN KEY (survey_type_id) REFERENCES survey_type (id)
);

CREATE INDEX ix_survey_survey_type ON survey (survey_type_id);

COMMENT ON TABLE  survey       IS 'Coleta de preços em uma data. Ex: 2025-05-06 Semanal, 2025-12-25 Natal';
COMMENT ON COLUMN survey.draft IS 'true enquanto a coleta não foi publicada';

-- No ON DELETE CASCADE: a survey that has survey items cannot be deleted.
CREATE TABLE survey_item (
    id                bigint  GENERATED BY DEFAULT AS IDENTITY,
    survey_id         integer NOT NULL,
    product_brand_id  integer NOT NULL,

    CONSTRAINT pk_survey_item                      PRIMARY KEY (id),
    CONSTRAINT uq_survey_item_survey_product_brand UNIQUE (survey_id, product_brand_id),
    CONSTRAINT fk_survey_item_survey               FOREIGN KEY (survey_id)        REFERENCES survey (id),
    CONSTRAINT fk_survey_item_product_brand        FOREIGN KEY (product_brand_id) REFERENCES product_brand (id)
);

CREATE INDEX ix_survey_item_product_brand ON survey_item (product_brand_id);

COMMENT ON TABLE survey_item IS 'Levantamento: um produto + marca dentro de uma coleta';

CREATE TABLE survey_item_price (
    survey_item_id  bigint        NOT NULL,
    store_id        smallint      NOT NULL,
    price           numeric(10,2) NOT NULL,

    CONSTRAINT pk_survey_item_price             PRIMARY KEY (survey_item_id, store_id),
    CONSTRAINT fk_survey_item_price_survey_item FOREIGN KEY (survey_item_id) REFERENCES survey_item (id),
    CONSTRAINT fk_survey_item_price_store       FOREIGN KEY (store_id)       REFERENCES store (id),
    CONSTRAINT ck_survey_item_price_price       CHECK (price > 0)
);

CREATE INDEX ix_survey_item_price_store ON survey_item_price (store_id);

COMMENT ON TABLE survey_item_price IS 'Preço do levantamento em cada mercado. Ex: Tauste R$ 25,00, Bom Lugar R$ 22,00';

-- ---------------------------------------------------------------------
-- Result
-- ---------------------------------------------------------------------

CREATE TABLE result (
    survey_item_id      bigint        NOT NULL,
    average_price       numeric(12,4) NOT NULL,
    lowest_price        numeric(10,2) NOT NULL,
    highest_price       numeric(10,2) NOT NULL,
    difference_amount   numeric(10,2) NOT NULL,
    difference_percent  numeric(7,4)  NOT NULL,

    CONSTRAINT pk_result                PRIMARY KEY (survey_item_id),
    CONSTRAINT fk_result_survey_item    FOREIGN KEY (survey_item_id) REFERENCES survey_item (id) ON DELETE CASCADE,
    CONSTRAINT ck_result_lowest_highest CHECK (lowest_price <= highest_price),
    CONSTRAINT ck_result_difference     CHECK (difference_amount >= 0 AND difference_percent >= 0)
);

COMMENT ON TABLE  result                    IS 'Resultado final do levantamento: média, menor, maior e diferença';
COMMENT ON COLUMN result.difference_percent IS 'Fração, não porcentagem: 0.4016 = 40,16%';

CREATE TABLE result_lowest_price (
    survey_item_id  bigint   NOT NULL,
    store_id        smallint NOT NULL,

    CONSTRAINT pk_result_lowest_price   PRIMARY KEY (survey_item_id, store_id),
    CONSTRAINT fk_rlp_result            FOREIGN KEY (survey_item_id)
        REFERENCES result (survey_item_id) ON DELETE CASCADE,
    CONSTRAINT fk_rlp_survey_item_price FOREIGN KEY (survey_item_id, store_id)
        REFERENCES survey_item_price (survey_item_id, store_id) ON DELETE CASCADE
);

CREATE INDEX ix_rlp_store ON result_lowest_price (store_id);

COMMENT ON TABLE result_lowest_price IS 'Mercados com o menor preço do levantamento (mais de um em caso de empate)';

-- ---------------------------------------------------------------------
-- Users, roles and permissions
-- ---------------------------------------------------------------------

CREATE TABLE role (
    id      smallint GENERATED BY DEFAULT AS IDENTITY,
    name    text     NOT NULL,
    active  boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_role      PRIMARY KEY (id),
    CONSTRAINT uq_role_name UNIQUE (name)
);

COMMENT ON TABLE role IS 'Função do usuário. Ex: ADMIN, PROFESSOR, ALUNO';

CREATE TABLE permission (
    id           smallint GENERATED BY DEFAULT AS IDENTITY,
    description  text     NOT NULL,
    active       boolean  NOT NULL DEFAULT true,

    CONSTRAINT pk_permission             PRIMARY KEY (id),
    CONSTRAINT uq_permission_description UNIQUE (description)
);

COMMENT ON TABLE permission IS 'Ação permitida. Ex: cadastrar produto, editar produto, cadastrar usuário';

CREATE TABLE role_permission (
    role_id        smallint NOT NULL,
    permission_id  smallint NOT NULL,

    CONSTRAINT pk_role_permission            PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permission_role       FOREIGN KEY (role_id)       REFERENCES role (id),
    CONSTRAINT fk_role_permission_permission FOREIGN KEY (permission_id) REFERENCES permission (id)
);

CREATE INDEX ix_role_permission_permission ON role_permission (permission_id);

COMMENT ON TABLE role_permission IS 'Permissões atribuídas a cada função';

-- "user" is a reserved word in PostgreSQL, hence app_user.
CREATE TABLE app_user (
    id             integer     GENERATED BY DEFAULT AS IDENTITY,
    email          text        NOT NULL,
    password_hash  text        NOT NULL,
    role_id        smallint    NOT NULL,
    active         boolean     NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_app_user       PRIMARY KEY (id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email CHECK (email = lower(email)),
    CONSTRAINT fk_app_user_role  FOREIGN KEY (role_id) REFERENCES role (id)
);

CREATE INDEX ix_app_user_role ON app_user (role_id);

COMMENT ON TABLE app_user IS 'Usuário do sistema';

-- ---------------------------------------------------------------------
-- Audit
-- ---------------------------------------------------------------------

CREATE TABLE audit (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY,
    user_id      integer     NOT NULL,
    action       text        NOT NULL,
    entity       text        NOT NULL,
    entity_id    bigint      NOT NULL,
    data_before  jsonb,
    data_after   jsonb,
    created_at   timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_audit        PRIMARY KEY (id),
    CONSTRAINT fk_audit_user   FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT ck_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_audit_before CHECK ((action = 'INSERT') = (data_before IS NULL)),
    CONSTRAINT ck_audit_after  CHECK ((action = 'DELETE') = (data_after  IS NULL))
);

CREATE INDEX ix_audit_user   ON audit (user_id);
CREATE INDEX ix_audit_entity ON audit (entity, entity_id);

COMMENT ON TABLE  audit             IS 'Registro do que cada usuário fez';
COMMENT ON COLUMN audit.data_before IS 'Estado anterior. NULL só em INSERT';
COMMENT ON COLUMN audit.data_after  IS 'Estado posterior. NULL só em DELETE';